#!/usr/bin/env python3
"""Embed the authoritative UTF-8 teaching prompts in the native host."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FILES = {
    "nodeTemplate": "node-closed-world.md",
    "sessionTemplate": "session-open-world.md",
    "goalTemplate": "task-goal-template.md",
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    lines = ["-- Generated by scripts/embed_prompts_lean.py", "namespace Lojita.Session", ""]
    for name, filename in FILES.items():
        value = (ROOT / "prompts" / filename).read_text(encoding="utf-8")
        lines.extend([f"def {name} : String := {json.dumps(value, ensure_ascii=False)}", ""])
    lines.append("end Lojita.Session\n")
    expected = "\n".join(lines)
    target = ROOT / "Lojita/Session/PromptTemplates.lean"
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != expected:
            raise SystemExit("PromptTemplates.lean is stale. Run scripts/embed_prompts_lean.py")
    else:
        target.write_text(expected, encoding="utf-8")


if __name__ == "__main__":
    main()
