"""Compile the pure workbench and link its generated CommonJS closure offline."""
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "tmp/js-build"
DIST = ROOT / "ui/dist/agda-bundle.js"
ENTRY = "jAgda.UI.OperadApp"
HOOKS = {"initWorkbench", "renderWorkbenchWire", "clickWorkbench", "panWorkbench",
         "tickWorkbench", "resizeWorkbench"}
REQUIRE = re.compile(r"""\brequire\s*\(\s*(["'])([\w.-]+)\1\s*\)""")
LOADER = """(function () {
"use strict";
const factories = Object.create(null), cache = Object.create(null);
function __agdaDefine(name, factory) { factories[name] = factory; }
function __agdaRequire(name) {
  if (cache[name]) return cache[name].exports;
  if (!factories[name]) throw new Error("Missing Agda module " + name);
  const mod = {exports: {}};
  cache[name] = mod;
  factories[name](mod, mod.exports, __agdaRequire);
  return mod.exports;
}
"""


def runtime_primitives(name, source):
    # Agda 2.6.3 leaves these Char primitives undefined on its JS backend.
    # Char is a Unicode scalar and Nat is a BigInt in the compiler's ABI.
    if name == "jAgda.Agda.Builtin.Char":
        for key, impl in {
            "primCharToNat": "c => BigInt(c.codePointAt(0))",
            "primNatToChar": "n => String.fromCodePoint(Number(n % 0x110000n))",
        }.items():
            source = source.replace(f'exports["{key}"] = undefined;', f'exports["{key}"] = {impl};')
    if name == "jAgda.Agda.Builtin.String":
        source = source.replace('return x.split("");', "return Array.from(x);")
    return source


def main():
    BUILD.mkdir(parents=True, exist_ok=True)
    subprocess.run(["agda", "--js", "-i", ".", "-i", "/usr/share/agda-stdlib",
                    "--compile-dir=tmp/js-build", "UI/OperadApp.agda"], cwd=ROOT, check=True)
    modules = {}
    edges = set()
    pending = [ENTRY, "agda-rts"]
    while pending:
        name = pending.pop()
        if name in modules:
            continue
        source = runtime_primitives(name, (BUILD / (name + ".js")).read_text())
        deps = {dep for _, dep in REQUIRE.findall(source)}
        linked = REQUIRE.sub(lambda m: "__agdaRequire(" + json.dumps(m[2]) + ")", source)
        if re.search(r"\brequire\s*\(", linked):
            raise ValueError(f"unsupported dynamic import in {name}")
        modules[name] = linked
        edges.update(deps)
        pending.extend(sorted(deps - modules.keys()))
    if edges - modules.keys():
        raise ValueError(f"missing modules: {edges - modules.keys()}")
    exports = set(re.findall(r'exports\["(\w+)"\]\s*=', modules[ENTRY]))
    calls = set(re.findall(r"\bapi\.(\w+)\s*\(", (ROOT / "ui/web-relay.js").read_text()))
    if not HOOKS <= exports or calls != HOOKS:
        raise ValueError(f"hook mismatch: missing exports {HOOKS - exports}, relay difference {calls ^ HOOKS}")
    result = [LOADER]
    for name, source in sorted(modules.items()):
        result.extend(["__agdaDefine(" + json.dumps(name) + ", function(module, exports, __agdaRequire) {\n",
                       source, "\n});\n"])
    result.append('window.AgdaOperadApp = __agdaRequire("jAgda.UI.OperadApp");\n})();\n')

    # The generated bytes live under tmp. The hard link is a directly copyable
    # static asset, and publishing by rename keeps a previous build usable.
    DIST.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=BUILD) as staging:
        bundle = Path(staging) / "agda-bundle.js"
        bundle.write_text("".join(result))
        link = Path(staging) / "publish.js"
        os.link(bundle, link)
        bundle.replace(BUILD / "agda-bundle.js")
        link.replace(DIST)
    print(f"Bundled {len(modules)} modules and {len(HOOKS)} workbench hooks into {DIST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
